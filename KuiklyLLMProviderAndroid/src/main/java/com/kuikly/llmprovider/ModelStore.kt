package com.kuikly.llmprovider

import android.content.Context
import org.json.JSONArray
import org.json.JSONObject
import java.io.File
import java.io.FileOutputStream
import java.net.HttpURLConnection
import java.net.URL
import java.security.MessageDigest
import java.util.concurrent.ConcurrentHashMap
import java.util.concurrent.CountDownLatch
import java.util.concurrent.TimeUnit

internal data class CatalogEntry(
    val id: String, val name: String, val file: String, val bytes: Long,
    val sha256: String, val url: String, val urlBackup: String, val bundled: Boolean,
)

/**
 * Model management for Android. Reads catalog.json (generated by scripts/prepare-variant.sh),
 * downloads with HTTP Range resume, silently merges bundled parts during start(),
 * and exposes a JSON snapshot to the cross-platform Module.
 */
internal class ModelStore(internal val ctx: Context) {

    companion object {
        @Volatile
        private var shared: ModelStore? = null

        /**
         * 同一个进程内的所有扩展 Module 实例共用一个模型状态。
         * 扩展 Module 由注册工厂按需创建，启动服务与查询状态可能落在不同实例上；
         * 共享状态可保证 active 标记与下载进度对每次查询一致。
         */
        fun instance(context: Context): ModelStore =
            shared ?: synchronized(this) {
                shared ?: ModelStore(context.applicationContext).also { shared = it }
            }

        /** 服务停止后以引擎实际状态（空串）回填；stop 不依赖 context，store 尚未创建时无需处理。 */
        fun onServiceStopped() {
            shared?.activeId = LLMProviderNativeBridge.modelId()
        }

        private val GGUF_MAGIC = "GGUF".toByteArray(Charsets.US_ASCII)
    }

    /** 单个下载任务的可取消状态：写线程句柄 + 完成栅栏，用于取消时先停线程再删文件。 */
    private class Job(@Volatile var running: Boolean = true) {
        @Volatile var conn: HttpURLConnection? = null
        val done = CountDownLatch(1)
    }

    internal val dir = File(ctx.filesDir, "models").apply { mkdirs() }
    internal val catalog = ArrayList<CatalogEntry>()
    private val jobs = ConcurrentHashMap<String, Job>()
    @Volatile var activeId = ""
    @Volatile var lastError = ""

    init {
        val text = try {
            ctx.assets.open("catalog.json").bufferedReader().use { it.readText() }
        } catch (e: Exception) { "{\"models\":[]}" }
        val arr = JSONObject(text).optJSONArray("models") ?: JSONArray()
        for (i in 0 until arr.length()) {
            val o = arr.optJSONObject(i) ?: continue
            catalog.add(CatalogEntry(
                o.optString("id"), o.optString("name"), o.optString("file"),
                o.optLong("bytes"), o.optString("sha256"),
                o.optString("url_primary"), o.optString("url_backup"), o.optBoolean("bundled")))
        }
    }

    fun entry(id: String): CatalogEntry? = catalog.find { it.id == id }
    fun path(e: CatalogEntry) = File(dir, e.file)
    private fun part(e: CatalogEntry) = File(dir, e.file + ".part")

    /** 加锁防止并发调用同时以截断模式写同一个 .merging 文件。 */
    @Synchronized
    fun ensureBundled() = BundledPartsInstaller.install(this)

    fun firstReady(): CatalogEntry? = catalog.firstOrNull { isPlausible(path(it), it) }

    fun snapshot(): String {
        val arr = JSONArray()
        for (e in catalog) {
            val f = path(e); val p = part(e); val job = jobs[e.id]
            val downloaded = when {
                job?.running == true -> p.length()
                p.exists() -> p.length()
                f.exists() -> f.length()
                else -> 0L
            }
            val state = when {
                job?.running == true -> AndroidProviderContract.STATE_DOWNLOADING
                f.exists() && f.length() == e.bytes ->
                    if (e.id == activeId) AndroidProviderContract.STATE_ACTIVE else AndroidProviderContract.STATE_READY
                p.exists() -> AndroidProviderContract.STATE_PAUSED
                else -> AndroidProviderContract.STATE_NOT_AVAILABLE
            }
            // actions 与 state 统一取自契约常量。
            val actions = JSONArray()
            when (state) {
                AndroidProviderContract.STATE_DOWNLOADING -> {
                    actions.put(AndroidProviderContract.ACTION_PAUSE)
                    actions.put(AndroidProviderContract.ACTION_CANCEL)
                }
                AndroidProviderContract.STATE_PAUSED -> {
                    actions.put(AndroidProviderContract.ACTION_RESUME)
                    actions.put(AndroidProviderContract.ACTION_CANCEL)
                }
                AndroidProviderContract.STATE_READY -> {
                    actions.put(AndroidProviderContract.ACTION_SELECT)
                    if (!e.bundled) actions.put(AndroidProviderContract.ACTION_DELETE)
                }
                AndroidProviderContract.STATE_ACTIVE -> {
                    if (!e.bundled) actions.put(AndroidProviderContract.ACTION_DELETE)
                }
                else -> actions.put(AndroidProviderContract.ACTION_DOWNLOAD)
            }
            arr.put(JSONObject()
                .put("id", e.id).put("name", e.name).put("bytes", e.bytes)
                .put("state", state).put("downloaded", downloaded).put("total", e.bytes)
                .put("active", e.id == activeId).put("bundled", e.bundled)
                .put("actions", actions))
        }
        return JSONObject().put("models", arr).put("error", lastError).toString()
    }

    fun download(id: String, resume: Boolean) {
        val e = entry(id) ?: return
        val job = Job(true)
        // putIfAbsent 原子占位，消除 check-then-act 双线程写同一 .part。
        if (jobs.putIfAbsent(id, job) != null) return
        Thread({
            try {
                lastError = ""
                val p = part(e)
                // 主源不可用时换备用源一次。两镜像同一 sha256、字节一致，续传沿用 .part 偏移。
                val sources = listOf(e.url, e.urlBackup).filter { it.isNotEmpty() }.distinct()
                for (source in sources) {
                    // 换源窗口内被暂停/取消：不保留上一个源留下的错误。
                    if (!job.running) { lastError = ""; break }
                    if (!downloadFrom(e, p, job, source, resume)) break
                }
            } catch (ex: Exception) {
                // 读流中途断开不换源：保留 .part 由用户续传。
                // 取消/暂停触发的 disconnect 会抛异常，此时不污染 lastError。
                if (job.running) lastError = ex.message ?: "download failed"
            } finally {
                jobs.remove(id, job)
                job.done.countDown()
            }
        }, "provider-download").apply { isDaemon = true }.start()
    }

    /**
     * 从单个源下载一次。返回 true 表示可以换源：连接失败 / 非 2xx（.part 原样保留），
     * 或全新下载内容不符（.part 已删）。成功、续传内容不符、暂停/取消均返回 false。
     */
    private fun downloadFrom(e: CatalogEntry, p: File, job: Job, source: String, resume: Boolean): Boolean {
        try {
            val existing = if (p.exists()) p.length() else 0L
            var append = resume && existing > 0 && existing < e.bytes

            fun open(range: Boolean): HttpURLConnection =
                (URL(source).openConnection() as HttpURLConnection).apply {
                    requestMethod = "GET"
                    connectTimeout = 15_000
                    readTimeout = 60_000
                    if (range) setRequestProperty("Range", "bytes=$existing-")
                }.also { job.conn = it }

            var code = 0
            val c = try {
                var conn = open(append)
                code = conn.responseCode
                // 续传必须返回 206 且 Content-Range 起点与本地偏移一致，否则同源改为完整重新下载。
                if (append && (code != 206 || contentRangeStart(conn.getHeaderField("Content-Range")) != existing)) {
                    try { conn.disconnect() } catch (_: Exception) {}
                    append = false
                    conn = open(false)
                    code = conn.responseCode
                }
                conn
            } catch (ex: Exception) {
                if (!job.running) throw ex  // 暂停/取消：交外层处理，不记错误
                lastError = ex.message ?: "download failed"
                return true
            }
            if (code !in 200..299) {
                lastError = "HTTP $code"
                return true
            }
            // 与 stopJob 同锁：已暂停则不打开输出流，避免截断 .part。
            val output = synchronized(job) {
                if (!job.running) return false
                FileOutputStream(p, append)
            }
            lastError = ""  // 本源可用：清除上一个源留下的错误
            // getHeaderFieldLong 需 API 24，minSdk 23 改用字符串解析。
            val contentLength = c.getHeaderField("Content-Length")?.toLongOrNull() ?: -1L
            val expectedTotal = if (append) existing + contentLength else e.bytes
            output.use { out ->
                c.inputStream.use { input ->
                    val buf = ByteArray(64 * 1024)
                    while (job.running) {
                        val n = input.read(buf)
                        if (n < 0) break
                        out.write(buf, 0, n)
                    }
                    out.flush()
                }
            }
            if (!job.running) return false  // 暂停/取消：保留 .part
            val finalLen = p.length()
            val lenOk = finalLen == e.bytes && (expectedTotal <= 0 || finalLen == expectedTotal)
            if (lenOk && verify(p, e)) {
                // 原子落盘 + 检查返回值，避免 renameTo 静默失败导致模型丢失。
                if (!moveIntoPlace(p, path(e))) lastError = "model install failed"
                return false
            }
            lastError = "model verification failed"; p.delete()
            return !append  // 全新下载内容不符（错误页 / 劫持）才换源从头重新下载
        } finally {
            try { job.conn?.disconnect() } catch (_: Exception) {}
            job.conn = null
        }
    }

    /** 先停写线程（断开连接 + 等其释放文件句柄），再按需要删 .part，避免竞争。 */
    private fun stopJob(id: String, deletePart: Boolean) {
        val job = jobs.remove(id) ?: return
        synchronized(job) { job.running = false }  // 与打开输出流互斥
        try { job.conn?.disconnect() } catch (_: Exception) {}
        try {
            if (!job.done.await(2, TimeUnit.SECONDS)) {
                // 超时后连接已断开，写线程会尽快退出，避免长时间阻塞调用方。
            }
        } catch (ex: InterruptedException) {
            Thread.currentThread().interrupt()
        }
        if (deletePart) entry(id)?.let { part(it).delete() }
    }

    fun pause(id: String) = stopJob(id, false)

    fun cancel(id: String) = stopJob(id, true)

    fun select(id: String): Boolean {
        val e = entry(id) ?: return false
        val f = path(e)
        if (!isPlausible(f, e)) return false
        val ok = LLMProviderNativeBridge.loadModel(f.absolutePath, e.id) == 1
        // 先卸后载：失败时引擎已无模型，以引擎实际状态为准（为空串）。
        activeId = LLMProviderNativeBridge.modelId()
        if (!ok) lastError = "engine failed to load model"
        return ok
    }

    fun delete(id: String) {
        val e = entry(id) ?: return
        // 内置模型属于发布产物，不提供删除入口。
        if (e.bundled) return
        stopJob(id, true)
        if (activeId == id) {
            // 先卸载引擎再删文件：服务回到「无可用模型」状态。
            activeId = ""
            LLMProviderNativeBridge.loadModel("", "")
        }
        path(e).delete(); part(e).delete()
    }

    private fun contentRangeStart(value: String?): Long {
        if (value == null || !value.startsWith("bytes ")) return -1L
        val range = value.removePrefix("bytes ").substringBefore("/")
        return range.substringBefore("-").trim().toLongOrNull() ?: -1L
    }

    /**
     * src 与 dst 同在 models/ 目录，File.renameTo 即 rename(2)：同文件系统内原子替换已存在的 dst。
     * 不做 copy 降级：非原子写入会让最终路径出现未校验的半成品，破坏 [isPlausible] 的前提。
     */
    internal fun moveIntoPlace(src: File, dst: File): Boolean = src.renameTo(dst)

    /**
     * start / select 的轻量判定：size + GGUF 魔数。
     * 最终路径只经「size + SHA-256 严格校验后原子 rename」写入（下载完成 / 内置分卷首次合并），
     * 且位于应用私有目录，无需每次启动重新计算整文件哈希。
     */
    internal fun isPlausible(f: File, e: CatalogEntry): Boolean {
        if (f.length() != e.bytes) return false
        return try {
            val head = ByteArray(GGUF_MAGIC.size)
            f.inputStream().use { it.read(head) } == head.size && head.contentEquals(GGUF_MAGIC)
        } catch (ex: Exception) { false }
    }

    /** size + SHA-256 流式校验；catalog 的 sha256 恒非空，空值一律拒绝（fail-safe）。 */
    internal fun verify(f: File, e: CatalogEntry): Boolean {
        if (f.length() != e.bytes || e.sha256.isEmpty()) return false
        return try {
            val md = MessageDigest.getInstance("SHA-256")
            f.inputStream().use { s ->
                val buf = ByteArray(64 * 1024)
                while (true) { val n = s.read(buf); if (n < 0) break; md.update(buf, 0, n) }
            }
            val actual = md.digest().joinToString("") { "%02x".format(it) }
            constantTimeEquals(actual, e.sha256)
        } catch (ex: Exception) { false }
    }

    private fun constantTimeEquals(a: String, b: String): Boolean {
        if (a.length != b.length) return false
        var diff = 0
        for (i in a.indices) diff = diff or (a[i].code xor b[i].code)
        return diff == 0
    }
}
